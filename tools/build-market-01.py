PH = re.compile(r"\{[^{}]*\}")

rows = [json.loads(l) for l in open(SRC, encoding="utf-8") if l.strip()]
missing = [r["key"] for r in rows if r["key"] not in RU]
extra = [k for k in RU if k not in {r["key"] for r in rows}]
assert not missing, missing
assert not extra, extra

out = []
for r in rows:
    en, ru = r["en"], RU[r["key"]]
    assert ru.strip(), r["key"]
    assert sorted(PH.findall(en)) == sorted(PH.findall(ru)), (r["key"], PH.findall(en), PH.findall(ru))
    out.append({"ns": r["ns"], "key": r["key"], "ru": ru})

os.makedirs(os.path.dirname(DST), exist_ok=True)
with open(DST, "w", encoding="utf-8") as f:
    for o in out:
        f.write(json.dumps(o, ensure_ascii=False) + "\n")

print("rows in:", len(rows), "rows out:", len(out))
print("unique keys:", len({o['key'] for o in out}))
