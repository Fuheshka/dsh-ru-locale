rows = [json.loads(l) for l in open(SRC, encoding="utf-8")]
out, changed, kept = [], 0, 0
used = set()

for r in rows:
    new = O.get(r["key"], r["ru"])
    if r["key"] in O:
        used.add(r["key"])
    if new != r["ru"]:
        changed += 1
    else:
        kept += 1
    # плейсхолдеры должны совпадать с английским оригиналом
    ph_en = sorted(re.findall(r"\{[^}]+\}", r["en"]))
    ph_ru = sorted(re.findall(r"\{[^}]+\}", new))
    assert ph_en == ph_ru, (r["key"], ph_en, ph_ru)
    out.append({"ns": r["ns"], "key": r["key"], "ru": new})

missing = set(O) - used
assert not missing, f"unused overrides: {missing}"
assert len(out) == len(rows) == 265

with open(DST, "w", encoding="utf-8", newline="\n") as f:
    for o in out:
        f.write(json.dumps(o, ensure_ascii=False) + "\n")

print("written", len(out), "changed", changed, "kept", kept)
