PLACEHOLDER = re.compile(r"\{[^{}]+\}")

rows = [json.loads(line) for line in SRC.read_text(encoding="utf-8").splitlines() if line.strip()]

problems = []
out = []
for i, row in enumerate(rows):
    key = row["key"]
    if key not in RU:
        problems.append(f"нет перевода: строка {i} {key}")
        continue
    ru = RU[key]
    en_ph = sorted(PLACEHOLDER.findall(row.get("en") or ""))
    ru_ph = sorted(PLACEHOLDER.findall(ru))
    if en_ph != ru_ph:
        problems.append(f"плейсхолдеры: строка {i} {key}: {en_ph} != {ru_ph}")
    if not ru.strip() and (row.get("en") or "").strip():
        problems.append(f"пустой перевод: строка {i} {key}")
    out.append({"ns": row["ns"], "key": key, "ru": ru})

extra = set(RU) - {r["key"] for r in rows}
if extra:
    problems.append(f"лишние ключи: {sorted(extra)}")
if len(out) != len(rows):
    problems.append(f"строк {len(out)}, во входе {len(rows)}")

if problems:
    raise SystemExit("ПРОВЕРКА НЕ ПРОШЛА:\n" + "\n".join(problems))

DST.parent.mkdir(parents=True, exist_ok=True)
with DST.open("w", encoding="utf-8") as fh:
    for obj in out:
        fh.write(json.dumps(obj, ensure_ascii=False) + "\n")

print(f"OK: {len(out)} строк -> {DST}")
