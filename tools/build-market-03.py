PH = re.compile(r"\{[^{}]*\}")


def main() -> int:
    rows = [json.loads(line) for line in open(SRC, encoding="utf-8") if line.strip()]
    errors = []

    if set(RU) != {r["key"] for r in rows}:
        missing = {r["key"] for r in rows} - set(RU)
        extra = set(RU) - {r["key"] for r in rows}
        errors.append(f"набор ключей расходится: нет {sorted(missing)}, лишние {sorted(extra)}")

    out = []
    for i, r in enumerate(rows):
        ru = RU.get(r["key"])
        if not ru or not ru.strip():
            errors.append(f"{r['key']}: пустой перевод")
            continue
        if sorted(PH.findall(r["en"])) != sorted(PH.findall(ru)):
            errors.append(
                f"{r['key']}: плейсхолдеры {PH.findall(r['en'])} != {PH.findall(ru)}"
            )
        en_tail = r["en"][-1].isspace()
        ru_tail = ru[-1].isspace()
        if en_tail != ru_tail:
            errors.append(f"{r['key']}: несовпадение хвостового пробела")
        if "  " in ru:
            errors.append(f"{r['key']}: двойной пробел")
        out.append({"ns": r["ns"], "key": r["key"], "ru": ru})

    if errors:
        print("\n".join(errors))
        return 1

    with open(DST, "w", encoding="utf-8") as fh:
        for obj in out:
            fh.write(json.dumps(obj, ensure_ascii=False) + "\n")

    print(f"строк: {len(out)} (вход: {len(rows)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
