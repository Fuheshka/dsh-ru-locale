rows = [json.loads(l) for l in open(SRC, encoding="utf-8")]
vr = [r for r in rows if r["source"] == "vision-router"]

errors = []
ph = re.compile(r"\{[^{}]+\}")
for r in vr:
    if r["key"] not in RU:
        errors.append("MISSING KEY: " + r["key"])
        continue
    ru = RU[r["key"]]
    if sorted(ph.findall(r["en"])) != sorted(ph.findall(ru)):
        errors.append("PLACEHOLDER %s: %s vs %s" % (r["key"], ph.findall(r["en"]), ph.findall(ru)))
    if r["en"] != r["en"].strip() and (r["en"][:1].isspace() != ru[:1].isspace() or r["en"][-1:].isspace() != ru[-1:].isspace()):
        errors.append("EDGE-SPACE %s: %r vs %r" % (r["key"], r["en"], ru))
    if "  " in ru:
        errors.append("DOUBLE-SPACE: " + r["key"])
    if re.search(r"[A-Za-zА-Яа-я]+\b(you|your)\b", ru, re.I):
        errors.append("EN-GLOSS: " + r["key"])

extra = set(RU) - {r["key"] for r in vr}
if extra:
    errors.append("EXTRA KEYS: " + ", ".join(sorted(extra)))

if errors:
    print("\n".join(errors))
    sys.exit(1)

